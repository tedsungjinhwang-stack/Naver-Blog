def build_system_prompt(
    niche: Niche,
    seo_cfg: dict[str, Any],
    intent: Intent = Intent.HOMEFEED,
    knowledge_excerpt: str = "",
    voice_rule: str = "",
) -> str:
    body_min = seo_cfg.get("body_char_min", 1700)
    if intent == Intent.HOMEFEED:
        body_min = max(body_min, 2000)
    body_max = max(body_min, 3000)  # 권장 상한이 하한보다 작아지지 않게
    targets = (
        f"[분량/구성 목표]\n"
        f"- 본문 공백제외 {body_min:,}자 이상 (권장 {body_min:,}~{body_max:,}자)\n"
        f"- 소제목(##) {seo_cfg.get('min_headings', 3)}개 이상 + 목차\n"
        f"- 태그 {seo_cfg.get('tags_min', 5)}~{seo_cfg.get('tags_max', 10)}개\n"
        f"- 이미지 가이드 {seo_cfg.get('min_images', 6)}개 이상(직접 촬영/제작 권장)\n"
        f"- 핵심 키워드는 본문에 {seo_cfg.get('primary_keyword_min_count', 3)}"
        f"~{seo_cfg.get('primary_keyword_max_count', 6)}회 자연스럽게 (스터핑 금지)\n"
    )
    parts = [
        (voice_rule.strip() or DEFAULT_VOICE_RULE),
        BASE_SYSTEM_RULES,
        INTENT_GUIDANCE.get(intent, ""),
        NICHE_GUIDANCE.get(niche, ""),
        targets,
    ]
    if knowledge_excerpt.strip():
        parts.append("[추가 참고: 홈판/알고리즘 학습 요약]\n" + knowledge_excerpt.strip())
    return "\n\n".join(p for p in parts if p.strip())
